/* 확률 prob 인 자리에 bit 를 담을 때 드는 값. 1/16 비트 단위. */
uint32_t ingot_rc_price(uint16_t prob, int bit)
{
    uint32_t p = bit ? ((1u << 11) - prob) : prob;
    return rc_price[p >> 4];
}

