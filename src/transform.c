const uint16_t *ingot_zigzag_of(int n)
{
#if INGOT_BLK32
    if (n == 32) return ingot_zz32;
#endif
    return (n == 4) ? ingot_zz4 : (n == 8) ? ingot_zz8 : ingot_zz16;
}

static const int16_t *dct_of(int n)
{
#if INGOT_BLK32
    if (n == 32) return &ingot_dct32[0][0];
#endif
    return (n == 4) ? &ingot_dct4[0][0]
         : (n == 8) ? &ingot_dct8[0][0] : &ingot_dct16[0][0];
}

#define MAT_V(n, tx) (((void)(tx)), dct_of(n))
#define MAT_H(n, tx) (((void)(tx)), dct_of(n))

void ingot_fdct(const int16_t *src, int stride, int16_t *dst, int n, int tx)
{
    int32_t tmp[INGOT_MAX_BLOCK * INGOT_MAX_BLOCK];
    const int16_t *Mh = MAT_H(n, tx), *Mv = MAT_V(n, tx);
    int shift = (n == 4) ? INGOT_FWD_SHIFT4
              : (n == 8) ? INGOT_FWD_SHIFT8
              : (n == 16) ? INGOT_FWD_SHIFT16 : INGOT_FWD_SHIFT32;
    int u, v, x, y;

    for (y = 0; y < n; y++) {
        const int16_t *row = src + (size_t)y * stride;
        for (u = 0; u < n; u++) {
            int32_t s = 0;
            for (x = 0; x < n; x++)
                s += (int32_t)Mh[u * n + x] * row[x];
            tmp[y * n + u] = s;
        }
    }
    for (v = 0; v < n; v++) {
        for (u = 0; u < n; u++) {
            int32_t s = 0;
            for (y = 0; y < n; y++)
                s += (int32_t)Mv[v * n + y] * tmp[y * n + u];
            s = (s + (1 << (shift - 1))) >> shift;
            if (s >  32767) s =  32767;
            if (s < -32768) s = -32768;
            dst[v * n + u] = (int16_t)s;
        }
    }
}

void ingot_idct(const int16_t *src, int16_t *dst, int stride, int n, int tx)
{
    /* 64비트로 모은다. 계수가 규격 상한(±32767)까지 찬 16x16 을 역변환하면
     * 둘째 단계 누산이 32비트 한계의 31.6 배까지 간다. 정상 이미지에서는
     * 안 닿지만 손상된 파일이 그 값을 실을 수 있고, 32비트로 두면 그때
     * 동작이 컴파일러 재량이 된다 — "어떤 바이트열에도 안 죽는다"는 약속이
     * 거기서 깨진다 (2026-08-22). 순변환은 입력이 잔차(±255)라 안전하다. */
    int64_t tmp[INGOT_MAX_BLOCK * INGOT_MAX_BLOCK];
    const int16_t *Mh = MAT_H(n, tx), *Mv = MAT_V(n, tx);
    int shift = (n == 4) ? INGOT_INV_SHIFT4
              : (n == 8) ? INGOT_INV_SHIFT8
              : (n == 16) ? INGOT_INV_SHIFT16 : INGOT_INV_SHIFT32;
    int u, v, x, y;

    for (u = 0; u < n; u++) {
        for (y = 0; y < n; y++) {
            int64_t s = 0;
            for (v = 0; v < n; v++)
                s += (int64_t)Mv[v * n + y] * src[v * n + u];
            tmp[y * n + u] = s;
        }
    }
    for (y = 0; y < n; y++) {
        int16_t *row = dst + (size_t)y * stride;
        for (x = 0; x < n; x++) {
            int64_t s = 0;
            for (u = 0; u < n; u++)
                s += (int64_t)Mh[u * n + x] * tmp[y * n + u];
            s = (s + (1 << (shift - 1))) >> shift;
            if (s >  32767) s =  32767;
            if (s < -32768) s = -32768;
            row[x] = (int16_t)s;
        }
    }
}
